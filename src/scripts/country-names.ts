// Writes src/shared/country-names.generated.ts from CLDR. Run: `bun src/scripts/country-names.ts`.
// Hermes (the phone) has no Intl.DisplayNames, so the names are baked in at build time.
import { COUNTRY_CODES } from "../shared/onboarding.ts";
import { LANG_TAG } from "../shared/lang.ts";
import { LANGS } from "../shared/types.ts";

const regions = COUNTRY_CODES.filter((c) => c !== "other");
const table = Object.fromEntries(
  LANGS.map((lang) => {
    const dn = new Intl.DisplayNames([LANG_TAG[lang]], { type: "region" });
    return [lang, Object.fromEntries(regions.map((c) => [c, dn.of(c.toUpperCase())]))];
  }),
);

await Bun.write(
  new URL("../shared/country-names.generated.ts", import.meta.url),
  `// GENERATED by src/scripts/country-names.ts from CLDR — do not edit. country-names.test.ts fails on drift.
import type { Lang } from "./types.ts";

export const COUNTRY_NAMES: Record<Lang, Record<string, string>> = ${JSON.stringify(table, null, 2)};
`,
);
